//go:build ignore

// gen writes t2s.txt, the table Simplify converts with, from OpenCC's
// dictionaries (Apache-2.0, NOTICE) at the tag below:
//
//	go generate ./internal/hans                  # downloads them from GitHub
//	go run gen.go -dir path/to/OpenCC/data/dictionary
//
// The table is OpenCC's t2s (TSPhrases, then TSCharacters, first
// candidates), plus the few Taiwan and Hong Kong variants that t2s leaves
// alone though they are no Simplified Chinese (TWVariants, HKVariants
// reversed): 著 → 着, with the phrases where 著 stays (著名, 名著: OpenCC's
// TWVariantsRevPhrases, and keeps), in their Traditional and Simplified
// forms. The rest of the variant tables is left out: run on text that is
// already Simplified, it is wrong (么 → 幺 in 这么). Every value is resolved to a
// fixed point, so that one longest-match pass converts, and converting
// again changes nothing.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"unicode/utf8"
)

const tag = "ver.1.4.2" // commit 025f371dc76b598d77384fbdab90c937471844d8

// variants are the variant characters taken from TWVariants and
// HKVariants reversed that TSCharacters leaves as they are (all but 著
// only appear in Traditional text).
var variants = map[string]string{
	"著": "着",                     // TW: the particle (看著); the phrases below keep 著
	"簷": "檐", "痺": "痹", "睪": "睾", // TW
	"衹": "只", "粧": "妆", "敍": "叙", "枱": "台", "糭": "粽", "衞": "卫", // HK
}

// keeps are more words where 著 is written so (zhù: to write, notable),
// VoxtMini's, beside OpenCC's: Traditional, then Simplified forms.
var keeps = []string{
	"土著", "卓著", "原著", "拙著", "撰著", "編著", "编著", "專著", "专著",
	"論著", "论著", "譯著", "译著", "遺著", "遗著",
}

func main() {
	dir := flag.String("dir", "", "OpenCC's data/dictionary (default: download "+tag+")")
	flag.Parse()
	read := func(name string) []byte {
		if *dir != "" {
			b, err := os.ReadFile(filepath.Join(*dir, name))
			if err != nil {
				log.Fatal(err)
			}
			return b
		}
		url := "https://raw.githubusercontent.com/BYVoid/OpenCC/" + tag + "/data/dictionary/" + name
		resp, err := http.Get(url)
		if err != nil {
			log.Fatal(err)
		}
		defer resp.Body.Close()
		if resp.StatusCode != 200 {
			log.Fatalf("%s: %s", url, resp.Status)
		}
		b, err := io.ReadAll(resp.Body)
		if err != nil {
			log.Fatal(err)
		}
		return b
	}
	chars := parse(read("TSCharacters.txt"))
	phrases := parse(read("TSPhrases.txt"))
	for k, v := range variants {
		if c, ok := chars[k]; ok && c != k {
			log.Fatalf("variant %s is converted by TSCharacters", k)
		}
		chars[k] = v
	}
	conv := func(s string) string { return convert(s, phrases, chars) }
	// 著's phrases: where it stays 著 (著名) or is written otherwise, in
	// their Traditional and Simplified forms, unless TSPhrases has them.
	keep := func(s string) string { // converted, 著 as it is
		return strings.ReplaceAll(conv(strings.ReplaceAll(s, "著", "\x00")), "\x00", "著")
	}
	for k, v := range parse(read("TWVariantsRevPhrases.txt")) {
		if !strings.Contains(k, "著") {
			continue
		}
		for _, key := range []string{k, keep(k)} {
			if _, ok := phrases[key]; !ok {
				phrases[key] = keep(v)
			}
		}
	}
	for _, k := range keeps {
		if _, ok := phrases[k]; ok {
			log.Fatalf("keep %s is in the phrases", k)
		}
		phrases[k] = keep(k)
	}
	// A fixed point: values converted until they change no more.
	for range 4 {
		for k, v := range chars {
			chars[k] = conv(v)
		}
		for k, v := range phrases {
			phrases[k] = conv(v)
		}
	}
	// A character that maps to itself is no conversion. (Phrases stay,
	// those that map to themselves too: they stop a shorter match.)
	for k, v := range chars {
		if k == v {
			delete(chars, k)
		}
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "# Generated by gen.go from OpenCC %s (Apache-2.0, NOTICE). Do not edit.\n", tag)
	fmt.Fprintf(&out, "# key<TAB>value: Traditional → Simplified; characters, then phrases.\n")
	for _, k := range sorted(chars) {
		fmt.Fprintf(&out, "%s\t%s\n", k, chars[k])
	}
	for _, k := range sorted(phrases) {
		fmt.Fprintf(&out, "%s\t%s\n", k, phrases[k])
	}
	if err := os.WriteFile("t2s.txt", out.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	// Idempotent: converting a value again changes nothing.
	for _, m := range []map[string]string{chars, phrases} {
		for k, v := range m {
			if again := conv(v); again != v {
				log.Printf("not a fixed point: %s → %s → %s", k, v, again)
			}
		}
	}
	log.Printf("t2s.txt: %d characters, %d phrases, %d bytes", len(chars), len(phrases), out.Len())
}

// parse reads an OpenCC dictionary: key, tab, candidates separated by
// spaces; the first candidate is the conversion.
func parse(b []byte) map[string]string {
	m := map[string]string{}
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "\t")
		if !ok {
			log.Fatalf("bad line %q", line)
		}
		v, _, _ = strings.Cut(v, " ")
		m[k] = v
	}
	return m
}

// convert is Simplify's longest match over the tables being built.
func convert(s string, phrases, chars map[string]string) string {
	maxLen := 1
	for k := range phrases {
		maxLen = max(maxLen, utf8.RuneCountInString(k))
	}
	rs := []rune(s)
	var b strings.Builder
	for i := 0; i < len(rs); {
		n := 0
		for l := min(maxLen, len(rs)-i); l >= 2; l-- {
			if v, ok := phrases[string(rs[i:i+l])]; ok {
				b.WriteString(v)
				n = l
				break
			}
		}
		if n == 0 {
			if v, ok := chars[string(rs[i])]; ok {
				b.WriteString(v)
			} else {
				b.WriteRune(rs[i])
			}
			n = 1
		}
		i += n
	}
	return b.String()
}

func sorted(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
